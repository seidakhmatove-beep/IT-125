const firstName = prompt("Введите ваше имя:");
const lastName = prompt("Введите вашу фамилию:");

if (firstName && lastName) {
    alert(`Здравствуйте, ${firstName} ${lastName}!`);
} else {
    alert("Вы не ввели имя или фамилию!");
}

